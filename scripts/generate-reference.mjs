function listTools(dir) {
  return new Promise((res, rej) => {
    const p = spawn('node', [join(dir, 'dist/index.js')], { stdio: ['pipe', 'pipe', 'pipe'] });
    const send = (m) => p.stdin.write(`${JSON.stringify({ jsonrpc: '2.0', ...m })}\n`);
    const timer = setTimeout(() => {
      p.kill();
      rej(new Error(`tools/list の応答が 20 秒以内に返りませんでした: ${dir}`));
    }, 20000);
    let buf = '';
    p.stdout.on('data', (d) => {
      buf += d;
      let i;
      while ((i = buf.indexOf('\n')) >= 0) {
        const line = buf.slice(0, i);
        buf = buf.slice(i + 1);
        let m;
        try {
          m = JSON.parse(line);
        } catch {
          continue;
        }
        if (m.id === 1) {
          send({ method: 'notifications/initialized' });
          send({ id: 2, method: 'tools/list', params: {} });
        }
        if (m.id === 2) {
          clearTimeout(timer);
          p.kill();
          res(m.result.tools);
        }
      }
    });
    p.on('error', rej);
    send({
      id: 1,
      method: 'initialize',
      params: { protocolVersion: '2025-03-26', capabilities: {}, clientInfo: { name: 'generate-reference', version: '0' } },
    });
  });
}

async function collect() {
  const servers = [];
  for (const id of SERVERS) {
    const dir = join(ROOT, 'mcp', `s1000d-${id}-mcp`);
    if (!existsSync(join(dir, 'dist/index.js'))) {
      console.error(`${dir}/dist/index.js がありません。MCP をビルドしてから実行してください。`);
      process.exit(1);
    }
    const pkg = readJson(join(dir, 'package.json'));
    const tools = (await listTools(dir)).map((t) => ({
      name: t.name,
      description: t.description,
      inputSchema: t.inputSchema,
      ...(t.annotations ? { annotations: t.annotations } : {}),
    }));
    servers.push({ id, package: pkg.name, version: pkg.version, tools });
    console.log(`${pkg.name}@${pkg.version}: ${tools.length} tools`);
  }
  writeJson(TOOLS_FILE, { $comment: 'scripts/generate-reference.mjs collect が tools/list の応答から作る。手で編集しない', servers });
}

