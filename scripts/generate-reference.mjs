/** 手書きの欄を、最初の「## 」より前（lead）と、節の並びに分ける */
function readNotes(name, lang) {
  const p = join(NOTES, `${name}.${lang}.md`);
  if (!existsSync(p)) return undefined;
  const text = readFileSync(p, 'utf8')
    .replace(/\r\n/g, '\n')
    .trim()
    // {{tool:server/name}} と {{attr:name}} を、その言語のページへのリンクにする
    .replace(/\{\{tool:([a-z]+)\/([a-z_]+)\}\}/g, (_, s, n) => `[\`${n}\`](${langBase(lang)}/reference/stack/${s}/${kebab(n)}/)`)
    .replace(/\{\{attr:([A-Za-z]+)\}\}/g, (_, n) => `[\`${n}\`](${langBase(lang)}/reference/s1000d/issue-${ISSUE}/${kebab(n)}/)`);
  const i = text.search(/^## /m);
  return i < 0 ? { lead: text, rest: '' } : { lead: text.slice(0, i).trim(), rest: text.slice(i).trim() };
}

/** 連続する single を「a〜b」にまとめる（同じ調整の値で、末尾の数字が続くもの） */
function groupValues(values) {
  const out = [];
  for (const v of values) {
    const last = out.at(-1);
    const m = /^(.*?)(\d+)$/.exec(v.value);
    if (last && v.form === 'single' && last.form === 'single' && last.tailoring === v.tailoring && m && last.prefix === m[1] && Number(m[2]) === last.n + 1) {
      last.to = v.value;
      last.n = Number(m[2]);
    } else {
      out.push({ ...v, from: v.value, to: v.value, prefix: m?.[1], n: m ? Number(m[2]) : NaN });
    }
  }
  return out;
}

