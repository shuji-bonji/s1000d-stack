function findInSpec(dir, test, depth = 0, out = []) {
  if (depth > 7) return out;
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    let st;
    try {
      st = statSync(p);
    } catch {
      continue;
    }
    if (test(p, name, st)) out.push(p);
    if (st.isDirectory() && name !== 'node_modules') findInSpec(p, test, depth + 1, out);
  }
  return out;
}

function specDir() {
  const fromArg = value('spec');
  if (fromArg) return resolve(fromArg);
  if (process.env.S1000D_SPEC_DIR && !process.env.S1000D_SPEC_DIR.includes('$')) return process.env.S1000D_SPEC_DIR;
  const cfg = process.env.S1000D_CONFIG ?? join(process.env.XDG_CONFIG_HOME ?? join(homedir(), '.config'), 's1000d-stack/config.json');
  if (existsSync(cfg)) {
    const c = readJson(cfg);
    if (c.specDir) return c.specDir;
  }
  return undefined;
}

const XS = 'http://www.w3.org/2001/XMLSchema';
const kids = (el, local) => {
  const out = [];
  for (let n = el.firstChild; n; n = n.nextSibling) if (n.nodeType === 1 && (!local || n.localName === local)) out.push(n);
  return out;
};
const desc = (el, local) => Array.from(el.getElementsByTagNameNS(XS, local));

function readSchema(doc) {
  const root = doc.documentElement;
  const simple = new Map(kids(root, 'simpleType').map((t) => [t.getAttribute('name'), t]));
  const complex = new Map(kids(root, 'complexType').map((t) => [t.getAttribute('name'), t]));
  const groups = new Map(kids(root, 'attributeGroup').map((t) => [t.getAttribute('name'), t]));
  const globalAttrs = new Map(kids(root, 'attribute').map((a) => [a.getAttribute('name'), a]));
  /** 型や属性グループの中の属性を、{ 名前 → 必須か } で返す（属性グループと基底型をたどる） */
  const attrsOf = (node, seen = new Set()) => {
    const out = new Map();
    const visit = (n) => {
      for (const c of kids(n)) {
        if (c.namespaceURI !== XS) continue;
        if (c.localName === 'attribute') {
          const name = c.getAttribute('ref') || c.getAttribute('name');
          if (name) out.set(name.replace(/^.*:/, ''), c.getAttribute('use') === 'required');
        } else if (c.localName === 'attributeGroup' && c.getAttribute('ref')) {
          const g = c.getAttribute('ref');
          if (!seen.has(`g:${g}`) && groups.has(g)) {
            seen.add(`g:${g}`);
            for (const [k, v] of attrsOf(groups.get(g), seen)) out.set(k, v);
          }
        } else if (c.localName === 'extension' || c.localName === 'restriction') {
          const b = c.getAttribute('base');
          if (b && complex.has(b) && !seen.has(`t:${b}`)) {
            seen.add(`t:${b}`);
            for (const [k, v] of attrsOf(complex.get(b), seen)) out.set(k, v);
          }
          visit(c);
        } else if (c.localName === 'complexContent' || c.localName === 'simpleContent') {
          visit(c);
        }
      }
    };
    visit(node);
    return out;
  };
  const elements = new Map();
  for (const e of kids(root, 'element')) {
    const name = e.getAttribute('name');
    const type = e.getAttribute('type');
    const inline = kids(e, 'complexType')[0];
    const t = inline ?? (type ? complex.get(type) : undefined);
    if (name && t) elements.set(name, attrsOf(t));
  }
  return { simple, globalAttrs, elements };
}

function constraintOf(schema, attr) {
  const a = schema.globalAttrs.get(attr);
  if (!a) return undefined;
  const type = a.getAttribute('type') ?? '';
  const st = schema.simple.get(type);
  if (!st) return { type };
  const base = desc(st, 'restriction')[0]?.getAttribute('base') ?? '';
  const enumeration = desc(st, 'enumeration').map((e) => e.getAttribute('value'));
  const pattern = desc(st, 'pattern').map((e) => e.getAttribute('value'));
  return { type, base, ...(enumeration.length ? { enumeration } : {}), ...(pattern.length ? { pattern } : {}) };
}

async function extract() {
  const spec = specDir();
  if (!spec || !existsSync(spec)) {
    console.log('仕様書の配布物の場所が分かりません（--spec、S1000D_SPEC_DIR、設定ファイルのどれも無い）。s1000d-issue-7.json は変えずに終わります。');
    return;
  }
  let xmldom;
  try {
    xmldom = createRequire(join(ROOT, 'lib/s1000d-core/package.json'))('@xmldom/xmldom');
  } catch {
    console.error('lib/s1000d-core の node_modules に @xmldom/xmldom がありません。lib/s1000d-core で npm install を実行してください。');
    process.exit(1);
  }
  const parse = (p) => new xmldom.DOMParser({ onError: () => {} }).parseFromString(readFileSync(p, 'utf8'), 'text/xml');
  const inDict = (p) => /data[_-]dictionary/i.test(p);
  const brexPath = findInSpec(spec, (p, n, st) => st.isFile() && /^DMC-S1000D-.*-04-10-0301-00A-022A-D_.*\.XML$/i.test(n) && !inDict(p))[0];
  const xsdDir = findInSpec(spec, (p, n, st) => st.isDirectory() && n === 'xml_schema_flat' && !inDict(p))[0];
  const defsPath = findInSpec(spec, (p, n) => n === 'attributesDefinition.xml')[0];
  if (!brexPath || !xsdDir || !defsPath) {
    console.error(`配布物の中に必要なものが見つかりません。既定 BREX: ${brexPath ?? '無い'}、XSD: ${xsdDir ?? '無い'}、データ辞書の定義: ${defsPath ?? '無い'}`);
    process.exit(1);
  }
  const ddFiles = join(dirname(defsPath), '..', 'attributes');
  const readme = join(dirname(defsPath), '..', '..', 'README.txt');
  const distributionDate = existsSync(readme) ? (readFileSync(readme, 'utf8').match(/\b(20\d\d-\d\d-\d\d)\b/)?.[1] ?? '') : '';
  const names = existsSync(NOTES)
    ? [...new Set(readdirSync(NOTES).filter((f) => /\.ja\.md$/.test(f)).map((f) => f.replace(/\.ja\.md$/, '')))].sort()
    : [];

  // XSD
  const xsdFiles = readdirSync(xsdDir).filter((f) => f.endsWith('.xsd')).sort();
  const schemas = xsdFiles.map((f) => ({ file: f, ...readSchema(parse(join(xsdDir, f))) }));

  // 既定 BREX
  const brex = parse(brexPath);
  const brexDmc = basename(brexPath).replace(/^DMC-/, '').replace(/_.*$/, '');
  const rules = Array.from(brex.getElementsByTagName('structureObjectRule')).map((r) => {
    const op = r.getElementsByTagName('objectPath')[0];
    let ctx = 'all';
    for (let n = r.parentNode; n; n = n.parentNode) {
      if (n.nodeName === 'contextRules') {
        ctx = n.getAttribute('rulesContext') ? basename(n.getAttribute('rulesContext')) : 'all';
        break;
      }
    }
    return {
      id: r.getElementsByTagName('brDecisionRef')[0]?.getAttribute('brDecisionIdentNumber') ?? '',
      objectPath: (op?.textContent ?? '').trim(),
      flag: op?.getAttribute('allowedObjectFlag') ?? '',
      context: ctx,
      // objectUse からは章と表の番号だけを取り出す（文は持ち出さない）
      refs: [...new Set(((r.getElementsByTagName('objectUse')[0]?.textContent ?? '').match(/Chap [\d.]+\d(?:, (?:Table|Para) [\d.]+\d)?/g) ?? []))],
      values: Array.from(r.getElementsByTagName('objectValue')).map((v) => ({
        value: v.getAttribute('valueAllowed') ?? '',
        form: v.getAttribute('valueForm') ?? '',
        tailoring: v.getAttribute('valueTailoring') || 'closed',
      })),
    };
  });

  // データ辞書の定義（章と Para の番号だけ）
  const defs = new Map();
  for (const n of Array.from(parse(defsPath).getElementsByTagName('name'))) {
    const p = n.parentNode;
    const get = (t) => (kids(p, t)[0]?.textContent ?? '').trim();
    defs.set((n.textContent ?? '').trim(), { chapter: get('chapter'), para: get('para') });
  }

  const attributes = names.map((name) => {
    const holders = new Map();
    let xsd;
    for (const s of schemas) {
      xsd ??= constraintOf(s, name);
      for (const [el, attrs] of s.elements) {
        if (!attrs.has(name)) continue;
        const h = holders.get(el) ?? { name: el, schemas: 0, required: true };
        h.schemas += 1;
        h.required &&= attrs.get(name);
        holders.set(el, h);
      }
    }
    const list = [...holders.values()].sort((a, b) => b.schemas - a.schemas || a.name.localeCompare(b.name));
    // XPath では @name のほかに attribute::name とも書かれる（例: BREX-S1-00117）
    const re = new RegExp(`(?:@|attribute::)${name}(?![A-Za-z0-9_])`);
    const mine = rules.filter((r) => re.test(r.objectPath));
    const isValueRule = (r) => r.values.length > 0 && new RegExp(`/@${name}$`).test(r.objectPath);
    const enumeration = xsd?.enumeration;
    return {
      name,
      slug: kebab(name),
      xsd: xsd
        ? {
            type: xsd.type,
            base: xsd.base ?? '',
            ...(enumeration
              ? enumeration.length > MAX_VALUES
                ? { enumerationCount: enumeration.length, enumerationFirst: enumeration[0], enumerationLast: enumeration.at(-1) }
                : { enumeration }
              : {}),
            ...(xsd.pattern ? { pattern: xsd.pattern } : {}),
          }
        : null,
      holders: { total: list.length, elements: list.slice(0, MAX_HOLDERS) },
      brex: {
        valueRules: mine.filter(isValueRule).map((r) => ({
          id: r.id,
          objectPath: r.objectPath,
          flag: r.flag,
          context: r.context,
          refs: r.refs,
          valueCount: r.values.length,
          ...(r.values.length <= MAX_VALUES ? { values: r.values } : {}),
          // XSD の列挙のうち、このルールが許可しない値（XSD の検証は通るが、照合では違反になる）
          ...(enumeration ? { notAllowed: summarize(enumeration.filter((v) => !allowedBy(r.values, v))) } : {}),
        })),
        relatedRuleIds: [...new Set(mine.filter((r) => !isValueRule(r)).map((r) => r.id))].sort(),
      },
      dictionary: { ...(defs.get(name) ?? { chapter: '', para: '' }), hasPage: existsSync(join(ddFiles, `${name}.xml`)) },
    };
  });
  writeJson(S1000D_FILE, {
    $comment: 'scripts/generate-reference.mjs extract が配布物から作る。手で編集しない。仕様書の文章は入れていない',
    issue: ISSUE,
    distributionDate,
    defaultBrex: brexDmc,
    schemaCount: xsdFiles.length,
    attributes,
  });
  console.log(`s1000d-issue-7.json: ${attributes.length} 属性（配布物の日付 ${distributionDate}、XSD ${xsdFiles.length} 本）`);
}

function allowedBy(values, v) {
  return values.some((x) => {
    if (x.form === 'single') return x.value === v;
    if (x.form === 'range') {
      const [a, b] = x.value.split('~');
      return a.length === v.length && a <= v && v <= b;
    }
    return x.form === 'pattern' ? new RegExp(`^(?:${x.value})$`).test(v) : false;
  });
}
function summarize(list) {
  return list.length ? { count: list.length, first: list[0], last: list.at(-1) } : { count: 0 };
}

