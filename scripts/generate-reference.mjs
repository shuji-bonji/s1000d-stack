/** mcp/<server>-mcp.md の「できること」の表から、ツールごとの手書きの概要を取る */
function summaries(server, lang) {
  const p = join(langDir(lang), 'mcp', `${server}-mcp.md`);
  const out = new Map();
  if (!existsSync(p)) return out;
  for (const line of readFileSync(p, 'utf8').split('\n')) {
    const m = /^\| (?:\[)?`([a-z_]+)`(?:\]\([^)]*\))? \| (.*) \|\s*$/.exec(line);
    if (m && !out.has(m[1])) out.set(m[1], m[2].trim());
  }
  return out;
}

function typeOf(p) {
  if (!p) return '';
  if (p.enum && !p.type) return 'enum';
  if (p.anyOf || p.oneOf) return (p.anyOf ?? p.oneOf).map(typeOf).filter(Boolean).join(' / ');
  if (p.type === 'array') return `array<${typeOf(p.items) || 'any'}>`;
  if (Array.isArray(p.type)) return p.type.join(' / ');
  return p.type ?? (p.$ref ? 'object' : '');
}

function flatten(schema, lang) {
  const defs = schema.$defs ?? {};
  const rows = [];
  const deref = (p, seen) => {
    let cur = p;
    let name;
    while (cur?.$ref) {
      name = cur.$ref.replace('#/$defs/', '');
      if (seen.has(name)) return { node: { ...defs[name], properties: undefined, items: undefined }, name, recursive: true };
      seen = new Set(seen).add(name);
      cur = { ...defs[name], ...(cur.description ? { description: cur.description } : {}) };
    }
    return { node: cur, name, seen };
  };
  const walk = (node, prefix, seen, depth) => {
    const required = new Set(node.required ?? []);
    for (const [k, raw] of Object.entries(node.properties ?? {})) {
      const { node: p, recursive, seen: s2 } = deref(raw, seen);
      const cons = [];
      if (p.enum) cons.push(p.enum.map((v) => code(JSON.stringify(v).replace(/^"|"$/g, ''))).join(' / '));
      if (p.default !== undefined) cons.push(`${lang === 'ja' ? '既定値' : 'default'} ${code(JSON.stringify(p.default))}`);
      if (p.pattern) cons.push(`${lang === 'ja' ? 'パターン' : 'pattern'} ${code(p.pattern)}`);
      if (p.minimum !== undefined) cons.push(`≥ ${p.minimum}`);
      if (p.maximum !== undefined) cons.push(`≤ ${p.maximum}`);
      if (p.minLength !== undefined) cons.push(`${lang === 'ja' ? '長さ' : 'length'} ≥ ${p.minLength}`);
      if (p.minItems !== undefined) cons.push(`${lang === 'ja' ? '件数' : 'items'} ≥ ${p.minItems}`);
      if (recursive) cons.push(lang === 'ja' ? '同じ形の入れ子' : 'nested, same shape');
      rows.push({ path: `${prefix}${k}`, type: typeOf(p), required: required.has(k), cons: cons.join(lang === 'ja' ? '、' : ', '), description: p.description ?? '' });
      if (recursive || depth >= 4) continue;
      if (p.properties) walk(p, `${prefix}${k}.`, s2 ?? seen, depth + 1);
      const it = p.type === 'array' && p.items ? deref(p.items, s2 ?? seen) : undefined;
      if (it && !it.recursive && it.node?.properties) walk(it.node, `${prefix}${k}[].`, it.seen ?? seen, depth + 1);
    }
  };
  walk(schema, '', new Set(), 0);
  return rows;
}

