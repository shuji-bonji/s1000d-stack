function build() {
  const files = new Map();
  const problems = [];
  const s1000d = existsSync(S1000D_FILE) ? readJson(S1000D_FILE) : { attributes: [] };
  const tools = existsSync(TOOLS_FILE) ? readJson(TOOLS_FILE) : { servers: [] };
  const toolNames = new Set(tools.servers.flatMap((s) => s.tools.map((t) => `${s.id}/${t.name}`)));
  const attrNames = new Set(s1000d.attributes.map((a) => a.name));

  for (const a of s1000d.attributes) {
    const heads = {};
    for (const lang of LANGS) {
      const page = s1000dPage(a, s1000d, lang);
      if (!page) {
        problems.push(`手書きの欄がありません: ${a.name}.${lang}.md`);
        continue;
      }
      heads[lang] = (page.match(/^## /gm) ?? []).length;
      files.set(join(langDir(lang), 'reference/s1000d', `issue-${ISSUE}`, `${a.slug}.md`), page);
    }
    if (heads.ja !== undefined && heads.en !== undefined && heads.ja !== heads.en) problems.push(`${a.name}: 見出しの数が日本語 ${heads.ja}、英語 ${heads.en} で違います`);
    // 手書きの欄に書いたツールと属性が、実際にあるか。日本語と英語で同じものを指しているか
    const marks = {};
    for (const lang of LANGS) {
      const p = join(NOTES, `${a.name}.${lang}.md`);
      if (!existsSync(p)) continue;
      const text = readFileSync(p, 'utf8');
      marks[lang] = [...text.matchAll(/\{\{(?:tool|attr):[^}]+\}\}/g)].map((m) => m[0]).sort().join(' ');
      for (const m of text.matchAll(/\{\{tool:([^}]+)\}\}/g)) if (toolNames.size && !toolNames.has(m[1])) problems.push(`${a.name}.${lang}.md: ツール ${m[1]} は tools/list にありません`);
      for (const m of text.matchAll(/\{\{attr:([^}]+)\}\}/g)) if (!attrNames.has(m[1])) problems.push(`${a.name}.${lang}.md: 属性 ${m[1]} のページがありません`);
    }
    if (marks.ja !== undefined && marks.en !== undefined && marks.ja !== marks.en) problems.push(`${a.name}: 手書きの欄が指すツールと属性が、日本語と英語で違います`);
  }
  if (existsSync(NOTES)) {
    const known = new Set(s1000d.attributes.map((a) => a.name));
    for (const f of readdirSync(NOTES)) {
      const m = /^(.*)\.(ja|en)\.md$/.exec(f);
      if (m && !known.has(m[1])) problems.push(`${f}: s1000d-issue-7.json にこの属性がありません。extract を実行してください`);
    }
  }

  for (const server of tools.servers) {
    for (const lang of LANGS) {
      const sum = summaries(server.id, lang);
      for (const tool of server.tools) {
        const related = s1000d.attributes.filter((a) => {
          const n = join(NOTES, `${a.name}.ja.md`);
          return existsSync(n) && readFileSync(n, 'utf8').includes(`{{tool:${server.id}/${tool.name}}}`);
        });
        if (!sum.has(tool.name)) problems.push(`mcp/${server.id}-mcp.md（${lang}）の表に ${tool.name} の行がありません`);
        files.set(join(langDir(lang), 'reference/stack', server.id, `${kebab(tool.name)}.md`), toolPage(server, tool, lang, sum.get(tool.name), related));
      }
    }
  }
  if (s1000d.attributes.length) for (const lang of LANGS) files.set(join(langDir(lang), 'reference/s1000d', `issue-${ISSUE}`, 'index.md'), s1000dIndex(s1000d, lang));
  if (tools.servers.length) for (const lang of LANGS) files.set(join(langDir(lang), 'reference/stack', 'index.md'), stackIndex(tools, lang));
  return { files, problems };
}

function generatedOnDisk() {
  const out = [];
  for (const lang of LANGS) {
    const dir = join(langDir(lang), 'reference');
    if (existsSync(dir)) findInSpec(dir, (p, n, st) => st.isFile() && n.endsWith('.md') && readFileSync(p, 'utf8').includes(MARK), 0, out);
  }
  return out;
}

function render(check) {
  const { files, problems } = build();
  let diff = 0;
  for (const [p, content] of files) {
    const cur = existsSync(p) ? readFileSync(p, 'utf8') : undefined;
    if (cur === content) continue;
    diff += 1;
    if (check) {
      console.log(`${cur === undefined ? '無い' : '違う'}: ${relative(ROOT, p)}`);
    } else {
      mkdirSync(dirname(p), { recursive: true });
      writeFileSync(p, content);
    }
  }
  for (const p of generatedOnDisk()) {
    if (files.has(p)) continue;
    diff += 1;
    if (check) console.log(`余分: ${relative(ROOT, p)}`);
    else rmSync(p);
  }
  for (const m of problems) console.log(`問題: ${m}`);
  console.log(check ? `${files.size} ページを比べ、差は ${diff} 件、問題は ${problems.length} 件でした。` : `${files.size} ページのうち ${diff} 件を書き換えました。問題は ${problems.length} 件です。`);
  if (check && (diff || problems.length)) process.exit(1);
  if (!check && problems.length) process.exitCode = 1;
}

const cmd = args.find((a) => !a.startsWith('--') && args[args.indexOf(a) - 1] !== '--spec' && args[args.indexOf(a) - 1] !== '--root');
if (args.includes('--check')) render(true);
else if (cmd === 'collect') await collect();
else if (cmd === 'extract') await extract();
else if (cmd === 'render') render(false);
else {
  console.log('使い方: node scripts/generate-reference.mjs collect | extract [--spec <dir>] | render | --check');
  process.exit(cmd ? 1 : 0);
}
